import { jsx as _jsx, jsxs as _jsxs, Fragment as _Fragment } from "react/jsx-runtime";
import { useEffect, useState, useRef } from "react";
import { motion } from "framer-motion";
import { FileText, Send, Copy, Check, Upload, Download } from "lucide-react";
import { Link } from "react-router-dom";
import { toast } from "sonner";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { resumeApi } from "@/api/resume";
import jsPDF from "jspdf";
import { sanitizeForPdf } from "@/utils/sanitizePdf";
const contentTypes = [
    { value: "cover_letter", label: "📝 Cover Letter", desc: "Professional cover letter for job application" },
    { value: "linkedin_summary", label: "💼 LinkedIn Summary", desc: "Optimized LinkedIn About section" },
    { value: "professional_bio", label: "👤 Professional Bio", desc: "Short professional biography" },
];
export function ContentGeneratorPage() {
    const [resumes, setResumes] = useState([]);
    const [selectedResumeId, setSelectedResumeId] = useState("");
    const [jobDescription, setJobDescription] = useState("");
    const [selectedType, setSelectedType] = useState("cover_letter");
    const [result, setResult] = useState(null);
    const [isLoading, setIsLoading] = useState(false);
    const [isGenerating, setIsGenerating] = useState(false);
    const [copied, setCopied] = useState(false);
    const contentRef = useRef(null);
    useEffect(() => {
        let cancelled = false;
        setIsLoading(true);
        resumeApi.getHistory()
            .then((data) => { if (cancelled)
            return; setResumes(data); if (data.length > 0)
            setSelectedResumeId(data[0].id); })
            .catch(() => { })
            .finally(() => { if (!cancelled)
            setIsLoading(false); });
        return () => { cancelled = true; };
    }, []);
    const handleGenerate = async () => {
        if (!selectedResumeId || !jobDescription.trim())
            return;
        setIsGenerating(true);
        toast.loading("AI is writing...", { id: "content" });
        try {
            const res = await resumeApi.generateContent(selectedResumeId, jobDescription, selectedType);
            setResult(res);
            toast.success(`${res.type} generated!`, { id: "content" });
        }
        catch {
            toast.error("Generation failed", { id: "content" });
        }
        finally {
            setIsGenerating(false);
        }
    };
    const handleCopy = () => {
        if (result) {
            navigator.clipboard.writeText(result.content);
            setCopied(true);
            toast.success("Copied to clipboard!");
            setTimeout(() => setCopied(false), 2000);
        }
    };
    const handleDownloadPDF = () => {
        if (!result)
            return;
        const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
        const pageWidth = doc.internal.pageSize.getWidth();
        const margin = 20;
        const maxWidth = pageWidth - margin * 2;
        // Header
        doc.setFillColor(79, 70, 229);
        doc.rect(0, 0, pageWidth, 28, "F");
        doc.setTextColor(255, 255, 255);
        doc.setFontSize(16);
        doc.setFont("helvetica", "bold");
        doc.text(sanitizeForPdf(result.type), pageWidth / 2, 12, { align: "center" });
        doc.setFontSize(10);
        doc.setFont("helvetica", "normal");
        doc.text(`Generated by ResumeAI  -  ${new Date().toLocaleDateString()}`, pageWidth / 2, 22, { align: "center" });
        // Body — sanitize AI text for Latin-1 font compatibility
        doc.setTextColor(31, 41, 55);
        doc.setFontSize(11);
        doc.setFont("helvetica", "normal");
        const lines = doc.splitTextToSize(sanitizeForPdf(result.content), maxWidth);
        let y = 40;
        for (const line of lines) {
            if (y > 275) {
                doc.addPage();
                y = 20;
            }
            doc.text(line, margin, y);
            y += 6;
        }
        // Footer on all pages
        const pages = doc.getNumberOfPages();
        for (let i = 1; i <= pages; i++) {
            doc.setPage(i);
            doc.setFontSize(8);
            doc.setTextColor(160, 160, 160);
            doc.text(`Page ${i} of ${pages}`, pageWidth / 2, 290, { align: "center" });
        }
        const typeName = result.type.replace(/\s+/g, "_");
        doc.save(`Generated_${typeName}.pdf`);
        toast.success("PDF downloaded!");
    };
    if (isLoading) {
        return (_jsxs("div", { className: "space-y-6", children: [_jsx("div", { className: "h-8 w-64 animate-pulse rounded-lg bg-gray-200 dark:bg-gray-800" }), _jsxs("div", { className: "grid gap-6 lg:grid-cols-2", children: [_jsx("div", { className: "h-[500px] animate-pulse rounded-2xl bg-gray-200 dark:bg-gray-800" }), _jsx("div", { className: "h-[500px] animate-pulse rounded-2xl bg-gray-200 dark:bg-gray-800" })] })] }));
    }
    if (resumes.length === 0) {
        return (_jsxs("div", { className: "flex flex-col items-center justify-center py-20", children: [_jsx(FileText, { className: "mb-4 h-16 w-16 text-gray-300 dark:text-gray-600" }), _jsx("h2", { className: "mb-2 text-xl font-semibold text-gray-900 dark:text-white", children: "No Resumes Found" }), _jsx("p", { className: "mb-6 text-gray-500", children: "Upload a resume first" }), _jsx(Link, { to: "/upload", children: _jsxs(Button, { className: "gap-2", children: [_jsx(Upload, { className: "h-4 w-4" }), " Upload Resume"] }) })] }));
    }
    return (_jsxs("div", { className: "space-y-6", children: [_jsxs(motion.div, { initial: { opacity: 0, y: 20 }, animate: { opacity: 1, y: 0 }, children: [_jsx("h1", { className: "text-2xl font-bold text-gray-900 dark:text-white", children: "AI Content Generator" }), _jsx("p", { className: "text-gray-500 dark:text-slate-400", children: "Generate cover letters, LinkedIn summaries & professional bios" })] }), _jsxs("div", { className: "grid gap-6 lg:grid-cols-2", children: [_jsx(motion.div, { initial: { opacity: 0, x: -20 }, animate: { opacity: 1, x: 0 }, transition: { delay: 0.1 }, children: _jsxs(Card, { className: "h-full", children: [_jsxs(CardHeader, { children: [_jsx(CardTitle, { children: "Configuration" }), _jsx(CardDescription, { children: "Select resume, content type, and paste job description" })] }), _jsxs(CardContent, { className: "space-y-4", children: [_jsxs("div", { className: "space-y-1.5", children: [_jsx("label", { className: "block text-sm font-medium text-gray-700 dark:text-gray-300", children: "Resume" }), _jsx("select", { value: selectedResumeId, onChange: (e) => setSelectedResumeId(e.target.value), className: "flex h-10 w-full rounded-lg border border-gray-300 bg-white px-3 py-2 text-sm shadow-sm focus:border-brand-500 focus:outline-none focus:ring-2 focus:ring-brand-500/20 dark:border-gray-600 dark:bg-gray-800 dark:text-gray-100", children: resumes.map((r) => _jsxs("option", { value: r.id, children: [r.fileName, " \u2014 ", new Date(r.createdAt).toLocaleDateString()] }, r.id)) })] }), _jsxs("div", { className: "space-y-1.5", children: [_jsx("label", { className: "block text-sm font-medium text-gray-700 dark:text-gray-300", children: "Content Type" }), _jsx("div", { className: "grid gap-2", children: contentTypes.map((ct) => (_jsxs("button", { onClick: () => { setSelectedType(ct.value); setResult(null); }, className: `rounded-xl border p-3 text-left transition-all ${selectedType === ct.value
                                                            ? "border-brand-500 bg-brand-50 ring-2 ring-brand-500/20 dark:bg-brand-900/20"
                                                            : "border-gray-200 hover:border-gray-300 dark:border-gray-700"}`, children: [_jsx("p", { className: "text-sm font-semibold text-gray-900 dark:text-white", children: ct.label }), _jsx("p", { className: "text-xs text-gray-500", children: ct.desc })] }, ct.value))) })] }), _jsxs("div", { className: "space-y-1.5", children: [_jsx("label", { className: "block text-sm font-medium text-gray-700 dark:text-gray-300", children: "Job Description" }), _jsx("textarea", { value: jobDescription, onChange: (e) => setJobDescription(e.target.value), placeholder: "Paste the job description here...", rows: 6, className: "w-full resize-none rounded-lg border border-gray-300 bg-white px-3 py-2 text-sm shadow-sm placeholder:text-gray-400 focus:border-brand-500 focus:outline-none focus:ring-2 focus:ring-brand-500/20 dark:border-gray-600 dark:bg-gray-800 dark:text-gray-100" })] }), _jsxs(Button, { className: "w-full gap-2 shadow-lg shadow-brand-500/25", onClick: handleGenerate, isLoading: isGenerating, disabled: !selectedResumeId || !jobDescription.trim(), children: [_jsx(Send, { className: "h-4 w-4" }), " Generate ", contentTypes.find((c) => c.value === selectedType)?.label.replace(/^.+\s/, "")] })] })] }) }), _jsx(motion.div, { initial: { opacity: 0, x: 20 }, animate: { opacity: 1, x: 0 }, transition: { delay: 0.2 }, children: _jsxs(Card, { className: "h-full", children: [_jsx(CardHeader, { children: _jsxs("div", { className: "flex items-center justify-between", children: [_jsx(CardTitle, { children: result?.type || "Generated Content" }), result && (_jsxs("div", { className: "flex items-center gap-2", children: [_jsxs(Button, { variant: "outline", size: "sm", className: "gap-1.5", onClick: handleDownloadPDF, children: [_jsx(Download, { className: "h-3 w-3" }), " PDF"] }), _jsx(Button, { variant: "outline", size: "sm", className: "gap-1.5", onClick: handleCopy, children: copied ? _jsxs(_Fragment, { children: [_jsx(Check, { className: "h-3 w-3" }), " Copied!"] }) : _jsxs(_Fragment, { children: [_jsx(Copy, { className: "h-3 w-3" }), " Copy"] }) })] }))] }) }), _jsx(CardContent, { children: result ? (_jsx(motion.div, { ref: contentRef, initial: { opacity: 0 }, animate: { opacity: 1 }, className: "whitespace-pre-wrap rounded-xl border border-gray-200 bg-gray-50 p-5 text-sm leading-relaxed text-gray-800 dark:border-gray-700 dark:bg-gray-800/50 dark:text-gray-200", children: result.content })) : (_jsxs("div", { className: "flex flex-col items-center justify-center py-16 text-center", children: [_jsx("span", { className: "mb-3 text-5xl", children: "\u2728" }), _jsx("p", { className: "text-sm text-gray-500", children: "Select options and click Generate" })] })) })] }) })] })] }));
}
